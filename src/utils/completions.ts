import { homedir } from 'node:os';
import { basename, isAbsolute, join } from 'node:path';
import { writeSetupFile } from './setupFiles';
import { logger } from '../logger';
export const SHELLS = ['bash', 'zsh', 'fish'] as const;
const scripts: Record<string, string> = {
  bash: `# Generated by Craft; commands and flags come from the installed CLI.
_craft_completion() {
  local item
  COMPREPLY=()
  while IFS= read -r item; do
    [[ "$item" == "\${COMP_WORDS[COMP_CWORD]}"* ]] && COMPREPLY+=("$item")
  done < <(SHELL=/bin/bash ZSH_NAME='' command "\${COMP_WORDS[0]}" --get-yargs-completions "\${COMP_WORDS[@]}" 2>/dev/null)
  return 0
}
complete -o bashdefault -o default -F _craft_completion craft sentry-craft
`,
  zsh: `#compdef craft sentry-craft
# Generated by Craft; commands and flags come from the installed CLI.
_craft_completion() {
  local -a reply
  reply=("\${(@f)$(SHELL=/bin/zsh COMP_CWORD="$((CURRENT-1))" command "\${words[1]}" --get-yargs-completions "\${words[@]}" 2>/dev/null)}")
  if (( \${#reply} )); then _describe 'Craft' reply; else _default; fi
}
if [[ \${zsh_eval_context[-1]} == loadautofunc ]]; then
  _craft_completion "$@"
else
  compdef _craft_completion craft sentry-craft
fi
`,
  fish: `# Generated by Craft; commands and flags come from the installed CLI.
function __craft_completion
  set -l words (commandline -opc)
  set -l current (commandline -ct)
  env SHELL=/bin/bash ZSH_NAME='' $words[1] --get-yargs-completions $words "$current" 2>/dev/null
end
complete -c craft -f -a '(__craft_completion)'
complete -c sentry-craft -f -a '(__craft_completion)'
`,
};
export function getCompletionScript(shell: string): string {
  if (!SHELLS.includes(shell as (typeof SHELLS)[number]))
    throw new Error(
      `Unsupported shell: ${shell}. Supported shells: ${SHELLS.join(', ')}`,
    );
  return scripts[shell];
}
export function detectCompletionShell(
  env: NodeJS.ProcessEnv = process.env,
): string | undefined {
  const shell = basename(env.SHELL || '').replace(/\.exe$/i, '');
  return SHELLS.includes(shell as (typeof SHELLS)[number]) ? shell : undefined;
}
export async function installCompletions(
  shell: string,
  env: NodeJS.ProcessEnv = process.env,
  home = homedir(),
): Promise<string[]> {
  const script = getCompletionScript(shell);
  const data =
    env.XDG_DATA_HOME && isAbsolute(env.XDG_DATA_HOME)
      ? env.XDG_DATA_HOME
      : join(home, '.local/share');
  const config =
    env.XDG_CONFIG_HOME && isAbsolute(env.XDG_CONFIG_HOME)
      ? env.XDG_CONFIG_HOME
      : join(home, '.config');
  const files =
    shell === 'bash'
      ? [
          join(data, 'bash-completion/completions/craft'),
          join(data, 'bash-completion/completions/sentry-craft'),
        ]
      : shell === 'zsh'
        ? [join(data, 'zsh/site-functions/_craft')]
        : [
            join(config, 'fish/completions/craft.fish'),
            join(config, 'fish/completions/sentry-craft.fish'),
          ];
  for (const file of files) await writeSetupFile(file, script);
  logger.info(`Completions: ${files.join(', ')}`);
  if (shell === 'bash')
    logger.info(
      `Load the completion file with: source '${files[0].replace(/'/g, "'\\''")}'`,
    );
  if (shell === 'zsh')
    logger.info(
      `Add ${join(data, 'zsh/site-functions')} to fpath before running compinit.`,
    );
  return files;
}
export async function configureCompletions(
  shell = detectCompletionShell(),
): Promise<void> {
  if (!shell) {
    logger.info(
      'To install completions, run craft setup --shell bash, zsh, or fish.',
    );
    return;
  }
  try {
    await installCompletions(shell);
  } catch (error) {
    logger.warn(`Shell completion setup failed: ${String(error)}`);
  }
}
