import { access, readFile, stat } from 'node:fs/promises';
import { constants } from 'node:fs';
import { homedir } from 'node:os';
import { isAbsolute, join } from 'node:path';
import skill from '../../skills/craft-cli/SKILL.md?raw';
import { getPackage } from './version';
import { writeSetupFile } from './setupFiles';
import { logger } from '../logger';

export function getAgentSkillContent(
  version = getPackage().version as string,
): string {
  return skill.replace(
    /version: ['"]__CRAFT_VERSION__['"]/,
    () => `version: ${JSON.stringify(version)}`,
  );
}
export async function installAgentSkills(
  enabled?: boolean,
  env: NodeJS.ProcessEnv = process.env,
  home = homedir(),
  version = getPackage().version as string,
): Promise<string[]> {
  const config =
    env.XDG_CONFIG_HOME && isAbsolute(env.XDG_CONFIG_HOME)
      ? env.XDG_CONFIG_HOME
      : join(home, '.config');
  const preference = join(config, 'craft/setup.json');
  let previous: boolean | undefined;
  try {
    const value: unknown = JSON.parse(await readFile(preference, 'utf8'));
    if (
      !value ||
      typeof value !== 'object' ||
      !('agentSkills' in value) ||
      typeof value.agentSkills !== 'boolean'
    )
      throw new Error();
    previous = value.agentSkills;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT')
      throw new Error(`Invalid agent-skills preference file: ${preference}`);
  }
  if (enabled !== undefined)
    await writeSetupFile(
      preference,
      JSON.stringify(
        { _comment: 'Generated by Craft', agentSkills: enabled },
        null,
        2,
      ) + '\n',
    );
  if ((enabled ?? previous) === false) {
    logger.info(
      'Agent skill installation/refresh is disabled. Re-enable with craft setup --agent-skills.',
    );
    return [];
  }
  const locations: string[] = [];
  for (const root of ['.agents', '.claude']) {
    const directory = join(home, root);
    try {
      if (!(await stat(directory)).isDirectory()) continue;
      await access(directory, constants.W_OK);
      const path = join(directory, 'skills/craft-cli/SKILL.md');
      await writeSetupFile(path, getAgentSkillContent(version));
      locations.push(path);
      logger.info(`Agent skill: ${path}`);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT')
        logger.warn(
          `Agent skill setup skipped for ${directory}: ${String(error)}`,
        );
    }
  }
  return locations;
}
export async function configureAgentSkills(enabled?: boolean): Promise<void> {
  try {
    await installAgentSkills(enabled);
  } catch (error) {
    logger.warn(`Agent skill setup failed: ${String(error)}`);
  }
}
