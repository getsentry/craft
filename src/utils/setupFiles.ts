import { lstat, readFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { dirname, join, basename } from 'node:path';
import { safeFs } from './dryRun';
import { isDryRun } from './helpers';
import { logger } from '../logger';

// Replace only files managed by Craft; never follow a destination symlink.
export async function writeSetupFile(
  path: string,
  content: string,
): Promise<void> {
  if (isDryRun()) {
    logger.info(`[dry-run] Would write ${path}`);
    return;
  }
  try {
    const stat = await lstat(path);
    if (stat.isSymbolicLink() || !stat.isFile())
      throw new Error(
        `Refusing symlink or non-file setup destination: ${path}`,
      );
    if (!(await readFile(path, 'utf8')).includes('Generated by Craft'))
      throw new Error(
        `Refusing to replace a custom file not managed by Craft: ${path}`,
      );
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  await safeFs.mkdir(dirname(path), { recursive: true });
  const stage = join(
    dirname(path),
    `.${basename(path)}.${randomBytes(12).toString('hex')}.tmp`,
  );
  try {
    await safeFs.writeFile(stage, content, { flag: 'wx', mode: 0o644 });
    await safeFs.rename(stage, path);
  } finally {
    await safeFs.rm(stage, { force: true });
  }
}
